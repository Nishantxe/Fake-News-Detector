"""
export_model.py  -  train the model in Python, then write assets/model.js for the website.

The website runs the finished model in JavaScript (GitHub Pages cannot run Python), so this script:
  1. trains TF-IDF + Passive Aggressive (main) and Logistic Regression (baseline)
  2. saves the vocabulary, IDF scores and learned word weights as assets/model.js

Usage
  python export_model.py                                    # demo data (built into fake_news_detector_pa.py)
  python export_model.py --fake Fake.csv --real True.csv    # real Kaggle data (recommended)

Then commit assets/model.js and push. The website picks it up automatically.
"""
import argparse
import datetime
import json

import numpy as np
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS, TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import train_test_split

from fake_news_detector_pa import clean_text, load_data, make_pa


def r(arr, nd=5):
    return [round(float(x), nd) for x in arr]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fake", help="path to Fake.csv")
    ap.add_argument("--real", help="path to True.csv")
    ap.add_argument("--max-features", type=int, default=20000,
                    help="keep only the N most common words/word pairs (keeps the website fast)")
    ap.add_argument("--min-df", type=int, default=None,
                    help="ignore terms found in fewer than N texts (default: 1 for demo, 2 for big data)")
    ap.add_argument("--pa-c", type=float, default=0.1, help="Passive Aggressive 'aggressiveness' (C)")
    ap.add_argument("--out", default="assets/model.js")
    args = ap.parse_args()

    using_csv = bool(args.fake and args.real)
    df = load_data(args.fake, args.real)
    df["content"] = df["content"].apply(clean_text)
    min_df = args.min_df if args.min_df is not None else (2 if len(df) > 5000 else 1)

    X_tr, X_te, y_tr, y_te = train_test_split(
        df["content"], df["label"], test_size=0.25, random_state=42, stratify=df["label"])

    # Same TF-IDF settings as the main script, plus max_features so the website stays small.
    vec = TfidfVectorizer(stop_words="english", ngram_range=(1, 2), max_df=0.9,
                          min_df=min_df, max_features=args.max_features)
    A_tr = vec.fit_transform(X_tr)
    A_te = vec.transform(X_te)

    pa = make_pa()
    pa.set_params(**({"C": args.pa_c} if "C" in pa.get_params() else {"eta0": args.pa_c}))
    pa.fit(A_tr, y_tr)
    lr = LogisticRegression(max_iter=1000).fit(A_tr, y_tr)

    metrics = {}
    for name, m in [("pa", pa), ("lr", lr)]:
        p = m.predict(A_te)
        metrics[name] = {"accuracy": round(float(accuracy_score(y_te, p)), 4),
                         "f1": round(float(f1_score(y_te, p)), 4)}
    print("Hidden-test results:", json.dumps(metrics))

    model = {
        "meta": {
            "source": "kaggle" if using_csv else "demo",
            "n_train": int(len(X_tr)), "n_test": int(len(X_te)),
            "n_terms": int(len(vec.vocabulary_)),
            "metrics": metrics,
            "built": datetime.date.today().isoformat(),
        },
        "terms": list(vec.get_feature_names_out()),
        "idf": r(vec.idf_),
        "stop": sorted(ENGLISH_STOP_WORDS),
        "pa": {"w": r(pa.coef_[0]), "b": round(float(pa.intercept_[0]), 5)},
        "lr": {"w": r(lr.coef_[0]), "b": round(float(lr.intercept_[0]), 5)},
    }
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("// Generated by export_model.py - do not edit by hand.\n")
        f.write("window.FND_MODEL = " + json.dumps(model, separators=(",", ":")) + ";\n")
    print(f"Wrote {args.out}  ({len(model['terms'])} terms)")


if __name__ == "__main__":
    main()
